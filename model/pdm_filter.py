"""Designs the filters mic.c uses for a mic that sends a raw one-bit stream (see mic.h).

    uv run pdm_filter.py        # rewrites firmware/audio/pdm_filter.h and prints the response

Stage 1 takes the 1.024 MHz bitstream down to 64 kHz, stage 2 takes that to 16 kHz.
"""

from __future__ import annotations

import numpy as np
from scipy import signal

from config import MODEL_DIR

BIT_RATE = 1_024_000
MID_RATE = 64_000
OUT_RATE = 16_000
STAGE1_TAPS = 96  # a whole number of bytes: the firmware filters a byte at a time
STAGE2_TAPS = 96
FULL_SCALE = 1 << 23  # an all-ones bitstream comes out as +2^23, the mic's 24-bit full scale
STAGE2_ONE = 1 << 15

HEADER = MODEL_DIR.parent / "firmware" / "audio" / "pdm_filter.h"


def design() -> tuple[np.ndarray, np.ndarray]:
    # Stage 1 only has to remove what would fold onto 0-8 kHz at 64 kHz: 56 kHz and up.
    h1 = signal.firwin(STAGE1_TAPS, 24_000, window=("kaiser", 10.0), fs=BIT_RATE)
    h1 = np.round(h1 / h1.sum() * FULL_SCALE).astype(np.int64)
    # Stage 2: flat to 7 kHz, down by 8.8 kHz (so 7.2-8 kHz picks up a little folding).
    h2 = signal.remez(STAGE2_TAPS, [0, 7_000, 8_800, MID_RATE / 2], [1, 0], weight=[1, 8], fs=MID_RATE)
    h2 = np.round(h2 / h2.sum() * STAGE2_ONE).astype(np.int64)
    return h1, h2


def decode(bits: np.ndarray) -> np.ndarray:
    """What the firmware computes, before its DC blocker: bits (0/1) in, 24-bit samples out."""
    h1, h2 = design()
    x = bits.astype(np.int64) * 2 - 1
    mid = np.convolve(x, h1[::-1], mode="valid")[::16]
    return (np.convolve(mid, h2[::-1], mode="valid")[::4]) >> 15


def write_header(h1: np.ndarray, h2: np.ndarray) -> None:
    def rows(values):
        text = [", ".join(str(int(v)) for v in values[i : i + 8]) for i in range(0, len(values), 8)]
        return "\n".join(f"\t{line}," for line in text)

    HEADER.write_text(
        "// Filter coefficients for the bitstream path in mic.c. Generated by model/pdm_filter.py;\n"
        "// do not edit by hand.\n\n"
        "#ifndef SERRA_PDM_FILTER_H\n#define SERRA_PDM_FILTER_H\n\n#include <stdint.h>\n\n"
        f"#define PDM_STAGE1_TAPS {len(h1)}\n#define PDM_STAGE2_TAPS {len(h2)}\n"
        f"#define PDM_STAGE2_SHIFT 15\n\n"
        "// Stage 1, oldest bit first. Sums to 2^23.\n"
        f"static const int32_t pdm_stage1[PDM_STAGE1_TAPS] = {{\n{rows(h1)}\n}};\n\n"
        "// Stage 2, oldest sample first. Sums to 2^15.\n"
        f"static const int16_t pdm_stage2[PDM_STAGE2_TAPS] = {{\n{rows(h2)}\n}};\n\n"
        "#endif // SERRA_PDM_FILTER_H\n"
    )


def main() -> None:
    h1, h2 = design()
    write_header(h1, h2)
    f = np.linspace(0, BIT_RATE / 2, 200_001)
    r1 = np.abs(signal.freqz(h1 / h1.sum(), worN=f, fs=BIT_RATE)[1])
    r2 = np.abs(signal.freqz(h2 / h2.sum(), worN=f % MID_RATE, fs=MID_RATE)[1])
    total = 20 * np.log10(np.maximum(r1 * r2, 1e-9))
    for hz in (100, 1000, 3000, 5000, 7000, 7500, 8000):
        print(f"{hz:>6} Hz: {total[np.argmin(np.abs(f - hz))]:6.2f} dB")
    print(f"worst leak from above 8.8 kHz: {total[f >= 8800].max():.1f} dB")
    print(f"stage 1 worst above 56 kHz: {20 * np.log10(r1[f >= 56_000].max()):.1f} dB")
    print(f"max |h2| {np.abs(h2).max()} (int16), wrote {HEADER}")


if __name__ == "__main__":
    main()
