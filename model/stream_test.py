"""Test the int8 model on a simulated live stream, the way a node runs it.

train.py scores isolated 1-second windows. A node instead slides its window along
continuous audio and infers every ~250 ms, so what matters in the field is per event:
was this call caught at all, and how often does the node cry wolf?

This lays test-set sounds (never used in training) end to end over background noise, one
every few seconds, runs the stream through the feature code and the model, and reports
events caught and false alerts per hour. Writes out/stream_report.md.

    uv run stream_test.py
    uv run stream_test.py --minutes 60
"""

from __future__ import annotations

import argparse
import json

import numpy as np

import features
import synth
from config import ALERT_CLASSES, CLASSES, CLIP, OUT, SAMPLE_RATE
from dataset import (
    SELF_NOISE_DB,
    active_span,
    background,
    load_clip,
    mswc_items,
    nonspeech_items,
    place,
    window_power,
)
from predict import HOP_FRAMES
from train import decide, run_tflite

SOURCES = ["whistle", "scream", "help", "other_speech", "nonspeech"]
GAP = (2.5, 5.0)  # seconds between event starts


def build_stream(minutes: float, rng: np.random.Generator):
    """Return (int16 audio, events), events being (source, first sample, last sample)."""
    n = int(minutes * 60) * SAMPLE_RATE
    clips: dict[str, list[str]] = {s: [] for s in SOURCES}
    for kind, path in mswc_items("test", rng) + nonspeech_items("test"):
        clips[kind].append(path)

    # Background changes every 20 s, level included.
    x = np.zeros(n, dtype=np.float32)
    levels = np.zeros(n, dtype=np.float32)
    for a in range(0, n, 20 * SAMPLE_RATE):
        b = min(n, a + 20 * SAMPLE_RATE)
        db = rng.uniform(-75, -40)
        x[a:b] = background(b - a, "test", rng) * 10 ** (db / 20)
        levels[a:b] = db
    x += rng.standard_normal(n).astype(np.float32) * 10 ** (SELF_NOISE_DB / 20)

    events = []
    at = 3 * SAMPLE_RATE
    while at < n - 2 * CLIP:
        source = SOURCES[rng.integers(len(SOURCES))]
        if source == "whistle":
            clip = synth.whistle_blast(rng.uniform(0.4, 1.0), rng)
        else:
            path = clips[source][rng.integers(len(clips[source]))]
            clip = place(load_clip(path), rng, loudest=source == "scream")
        # 5-35 dB above the local background, but never beyond a slight clip.
        clip = clip / (np.abs(clip).max() + 1e-9)
        loud_db = 10 * np.log10(window_power(clip, min(4800, len(clip))).max() + 1e-12)
        gain_db = min(levels[at] + rng.uniform(5, 35) - loud_db, 2.0)
        x[at : at + len(clip)] += clip * 10 ** (gain_db / 20)
        first, last = active_span(clip)
        events.append((source, at + first, at + last))
        at += int(rng.uniform(*GAP) * SAMPLE_RATE)
    return np.clip(x * 32768, -32768, 32767).astype(np.int16), events


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--minutes", type=float, default=30)
    ap.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()

    rng = np.random.default_rng(args.seed)
    pcm, events = build_stream(args.minutes, rng)

    frames = features.extract(pcm)
    starts = np.arange(0, len(frames) - features.FRAMES + 1, HOP_FRAMES)
    x = np.stack([frames[s : s + features.FRAMES] for s in starts])
    x = x.astype(np.float32)[..., None] / 255.0
    thresholds = json.loads((OUT / "thresholds.json").read_text())
    scores = run_tflite((OUT / "serra.tflite").read_bytes(), x)
    alerts = decide(scores, [thresholds[c] for c in ALERT_CLASSES])

    # A window "sees" an event if they overlap; alerts in windows that see no alert-class
    # event (or only the wrong class) are false. Consecutive false windows count once.
    win_a = starts * features.STEP
    win_b = win_a + CLIP
    claimed = np.zeros(len(starts), dtype=bool)
    rows = []
    for source in SOURCES:
        mine = [e for e in events if e[0] == source]
        hit = wrong = 0
        for _, first, last in mine:
            seen = (win_a < last) & (win_b > first)
            if source in ALERT_CLASSES:
                right = seen & (alerts == CLASSES.index(source))
                hit += bool(right.any())
                wrong += bool((seen & (alerts >= 0)).any() and not right.any())
                claimed |= seen & (alerts >= 0)
            else:
                wrong += bool((seen & (alerts >= 0)).any())
        rows.append((source, len(mine), hit, wrong))

    false = (alerts >= 0) & ~claimed
    bursts = int((false & ~np.r_[False, false[:-1]]).sum())
    hours = args.minutes / 60

    lines = [
        "# Stream test",
        "",
        (
            f"Generated by `stream_test.py`: {args.minutes:g} minutes of simulated live audio, "
            f"{len(events)} test-set sounds over changing background noise, int8 model, one "
            "inference every 240 ms."
        ),
        "",
        "| sound | events | caught | alerted as another class |",
        "|---|---:|---:|---:|",
    ]
    for source, total, hit, wrong in rows:
        if source in ALERT_CLASSES:
            lines.append(f"| {source} | {total} | {hit} ({hit / max(1, total):.0%}) | {wrong} |")
    lines += ["", "| non-alert sound | events | raised a false alert |", "|---|---:|---:|"]
    for source, total, _, wrong in rows:
        if source not in ALERT_CLASSES:
            name = "coughs, laughs, crying, ..." if source == "nonspeech" else source
            lines.append(f"| {name} | {total} | {wrong} ({wrong / max(1, total):.1%}) |")
    lines += [
        "",
        (
            f"False alerts in total: **{bursts}** in {args.minutes:g} minutes "
            f"({bursts / hours:.0f} per hour). Note how dense this stream is: a sound every "
            "few seconds, half of them speech or other human noise. A quiet trail is far "
            "easier."
        ),
        "",
    ]
    text = "\n".join(lines)
    (OUT / "stream_report.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
